    <script src="https://cdn.jsdelivr.net/npm/chart.js@4.4.0/dist/chart.umd.min.js"></script>
    <script>
        const cashFlowData = @json($cashFlowData);
        const categories   = @json($expensesByCategory->pluck('category'));
        const catTotals    = @json($expensesByCategory->pluck('total')->map(fn($v) => (float)$v));

        const isDark    = document.documentElement.classList.contains('dark');
        const gridColor = isDark ? 'rgba(255,255,255,0.06)' : 'rgba(0,0,0,0.06)';
        const tickColor = isDark ? '#94a3b8' : '#6b7280';

        // ── Cash Flow Chart ─────────────────────────────────────
        const allLabels     = [...cashFlowData.labels, ...cashFlowData.forecastLabels];
        const allIncome     = [...cashFlowData.incomeData,  ...cashFlowData.forecastIncome.map(() => null)];
        const allExpense    = [...cashFlowData.expenseData, ...cashFlowData.forecastExpense.map(() => null)];
        const forecastInc   = [...cashFlowData.incomeData.map(() => null), cashFlowData.incomeData.at(-1), ...cashFlowData.forecastIncome];
        const forecastExp   = [...cashFlowData.expenseData.map(() => null), cashFlowData.expenseData.at(-1), ...cashFlowData.forecastExpense];

        const cfCtx = document.getElementById('reportsCashFlowChart')?.getContext('2d');
        if (cfCtx) {
            new Chart(cfCtx, {
                type: 'line',
                data: {
                    labels: allLabels,
                    datasets: [
                        { label: 'Income', data: allIncome, borderColor: '#10b981', backgroundColor: 'rgba(16,185,129,0.07)', borderWidth: 2.5, pointRadius: 3, tension: 0.4, fill: true, spanGaps: false },
                        { label: 'Expenses', data: allExpense, borderColor: '#f87171', backgroundColor: 'rgba(248,113,113,0.06)', borderWidth: 2.5, pointRadius: 3, tension: 0.4, fill: true, spanGaps: false },
                        { label: 'Forecast Income', data: forecastInc, borderColor: '#10b981', borderWidth: 2, borderDash: [5,4], pointRadius: 2, tension: 0.4, fill: false, spanGaps: false },
                        { label: 'Forecast Expenses', data: forecastExp, borderColor: '#f87171', borderWidth: 2, borderDash: [5,4], pointRadius: 2, tension: 0.4, fill: false, spanGaps: false },
                    ]
                },
                options: {
                    responsive: true, maintainAspectRatio: false,
                    interaction: { mode: 'index', intersect: false },
                    plugins: {
                        legend: { labels: { color: tickColor, font: { size: 10 }, boxWidth: 10, padding: 12 } },
                        tooltip: {
                            callbacks: {
                                label: ctx => ctx.raw === null ? null : ` ${ctx.dataset.label}: Rs ${Number(ctx.raw).toLocaleString('en-IN')}`
                            }
                        }
                    },
                    scales: {
                        x: { grid: { color: gridColor }, ticks: { color: tickColor, font: { size: 10 } } },
                        y: { grid: { color: gridColor }, ticks: { color: tickColor, font: { size: 10 }, callback: v => 'Rs ' + Number(v).toLocaleString('en-IN', {maximumFractionDigits:0}) } }
                    }
                }
            });
        }

        // ── Pie Chart ────────────────────────────────────────────
        const pieCtx = document.getElementById('categoryPieChart')?.getContext('2d');
        if (pieCtx && categories.length > 0) {
            const pieColors = ['#22d3ee','#f87171','#a78bfa','#34d399','#fbbf24','#f472b6','#60a5fa','#fb923c'];
            new Chart(pieCtx, {
                type: 'doughnut',
                data: {
                    labels: categories,
                    datasets: [{
                        data: catTotals,
                        backgroundColor: pieColors.slice(0, categories.length),
                        borderWidth: 2,
                        borderColor: isDark ? '#0f172a' : '#ffffff',
                        hoverOffset: 6,
                    }]
                },
                options: {
                    responsive: true, maintainAspectRatio: false, cutout: '65%',
                    plugins: {
                        legend: { display: false },
                        tooltip: {
                            callbacks: {
                                label: ctx => ` ${ctx.label}: Rs ${Number(ctx.raw).toLocaleString('en-IN')}`
                            }
                        }
                    }
                }
            });
        }
    </script>

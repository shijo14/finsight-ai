    <!-- Map Initialization JavaScript -->
    <script>
        document.addEventListener('DOMContentLoaded', function() {
            const isGoogle = typeof google !== 'undefined' && typeof google.maps !== 'undefined';
            const competitors = @json($competitors);

            // Default center: coordinates for downtown city/general region (centered on NY if empty)
            let centerLat = 40.7128;
            let centerLng = -74.0060;

            if (competitors.length > 0) {
                let latSum = 0;
                let lngSum = 0;
                competitors.forEach(c => {
                    latSum += parseFloat(c.latitude);
                    lngSum += parseFloat(c.longitude);
                });
                centerLat = latSum / competitors.length;
                centerLng = lngSum / competitors.length;
            }

            if (isGoogle) {
                const mapEl = document.getElementById('map');
                if (!mapEl) return;
                const map = new google.maps.Map(mapEl, {
                    center: { lat: centerLat, lng: centerLng },
                    zoom: competitors.length > 0 ? 13 : 11,
                    styles: [
                        { "featureType": "water", "elementType": "geometry", "stylers": [{ "color": "#e9e9e9" }, { "lightness": 17 }] },
                        { "featureType": "landscape", "elementType": "geometry", "stylers": [{ "color": "#f5f5f5" }, { "lightness": 20 }] },
                        { "featureType": "road.highway", "elementType": "geometry.fill", "stylers": [{ "color": "#ffffff" }, { "lightness": 17 }] },
                        { "featureType": "road.highway", "elementType": "geometry.stroke", "stylers": [{ "color": "#ffffff" }, { "lightness": 29 }, { "weight": 0.2 }] },
                        { "featureType": "road.arterial", "elementType": "geometry", "stylers": [{ "color": "#ffffff" }, { "lightness": 18 }] },
                        { "featureType": "road.local", "elementType": "geometry", "stylers": [{ "color": "#ffffff" }, { "lightness": 16 }] },
                        { "featureType": "poi", "elementType": "geometry", "stylers": [{ "color": "#f5f5f5" }, { "lightness": 21 }] },
                        { "featureType": "poi.park", "elementType": "geometry", "stylers": [{ "color": "#dedede" }, { "lightness": 21 }] },
                        { "elementType": "labels.text.stroke", "stylers": [{ "visibility": "on" }, { "color": "#ffffff" }, { "lightness": 16 }] },
                        { "elementType": "labels.text.fill", "stylers": [{ "saturation": 36 }, { "color": "#333333" }, { "lightness": 40 }] },
                        { "elementType": "labels.icon", "stylers": [{ "visibility": "off" }] },
                        { "featureType": "transit", "elementType": "geometry", "stylers": [{ "color": "#f2f2f2" }, { "lightness": 19 }] },
                        { "featureType": "administrative", "elementType": "geometry.fill", "stylers": [{ "color": "#fefefe" }, { "lightness": 20 }] },
                        { "featureType": "administrative", "elementType": "geometry.stroke", "stylers": [{ "color": "#fefefe" }, { "lightness": 17 }, { "weight": 1.2 }] }
                    ]
                });

                const bounds = new google.maps.LatLngBounds();

                competitors.forEach(c => {
                    const position = { lat: parseFloat(c.latitude), lng: parseFloat(c.longitude) };
                    const marker = new google.maps.Marker({
                        position: position,
                        map: map,
                        title: c.name
                    });

                    bounds.extend(position);

                    const contentString = `
                        <div class="p-2 min-w-[200px]">
                            <span class="inline-block px-1.5 py-0.5 rounded text-[10px] font-semibold bg-neutral-200 dark:bg-white/10 text-neutral-800 dark:text-slate-200 mb-1">${c.name}</span>
                            <h3 class="font-bold text-sm text-neutral-900 dark:text-slate-100">${c.building_name}</h3>
                            <p class="text-[11px] text-neutral-500 dark:text-slate-400 mt-1">${c.address}</p>
                            <div class="mt-2 text-xs border-t pt-1.5 flex justify-between">
                                <span><strong>Rent:</strong> ${c.average_rent ? 'Rs ' + parseFloat(c.average_rent).toLocaleString() : 'N/A'}</span>
                                <span><strong>Occ:</strong> ${c.occupancy_rate ? c.occupancy_rate + '%' : 'N/A'}</span>
                            </div>
                            <a href="/competitors/${c.id}" class="mt-2.5 block text-center btn-primary rounded text-[11px] font-semibold py-1 transition">View Details</a>
                        </div>
                    `;

                    const infowindow = new google.maps.InfoWindow({
                        content: contentString
                    });

                    marker.addListener('click', () => {
                        infowindow.open(map, marker);
                    });
                });

                if (competitors.length > 1) {
                    map.fitBounds(bounds);
                }
            } else {
                const mapEl = document.getElementById('map');
                if (!mapEl) return;
                const map = L.map('map').setView([centerLat, centerLng], competitors.length > 0 ? 13 : 11);
                
                L.tileLayer('https://{s}.basemaps.cartocdn.com/rastertiles/voyager/{z}/{x}/{y}{r}.png', {
                    attribution: '&copy; <a href="https://www.openstreetmap.org/copyright">OpenStreetMap</a> contributors &copy; <a href="https://carto.com/attributions">CARTO</a>',
                    maxZoom: 20
                }).addTo(map);

                const markers = [];

                competitors.forEach(c => {
                    const contentString = `
                        <div class="p-1 min-w-[180px]">
                            <span class="inline-block px-1.5 py-0.5 rounded text-[10px] font-semibold bg-neutral-200 dark:bg-white/10 text-neutral-800 dark:text-slate-200 mb-1">${c.name}</span>
                            <h3 class="font-bold text-sm text-neutral-900 dark:text-slate-100">${c.building_name}</h3>
                            <p class="text-[11px] text-neutral-500 dark:text-slate-400 mt-1">${c.address}</p>
                            <div class="mt-2 text-xs border-t pt-1.5 flex justify-between">
                                <span><strong>Rent:</strong> ${c.average_rent ? 'Rs ' + parseFloat(c.average_rent).toLocaleString() : 'N/A'}</span>
                                <span><strong>Occ:</strong> ${c.occupancy_rate ? c.occupancy_rate + '%' : 'N/A'}</span>
                            </div>
                            <a href="/competitors/${c.id}" class="mt-2.5 block text-center btn-primary rounded text-[11px] font-semibold py-1 transition">View Details</a>
                        </div>
                    `;
                    const marker = L.marker([parseFloat(c.latitude), parseFloat(c.longitude)])
                        .addTo(map)
                        .bindPopup(contentString);
                    
                    markers.push(marker);
                });

                if (markers.length > 1) {
                    const group = new L.featureGroup(markers);
                    map.fitBounds(group.getBounds().pad(0.1));
                }
            }
        });
    </script>
